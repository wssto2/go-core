-- incidents: one problem however often it is seen. open_fingerprint is the fingerprint while the incident is open and
-- NULL after, so its unique index allows one open incident per fingerprint.
-- The DDL is what an application that grew the same tables under other names has once it renames them, so it can
-- adopt this file with MarkApplied.
CREATE TABLE IF NOT EXISTS `incidents` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `public_code` varchar(32) COLLATE utf8mb3_unicode_ci NOT NULL,
  `fingerprint` char(64) COLLATE utf8mb3_unicode_ci NOT NULL,
  `open_fingerprint` char(64) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `source` enum('user_report','runtime_error','mixed') COLLATE utf8mb3_unicode_ci NOT NULL DEFAULT 'runtime_error',
  `status` enum('new','triaged','in_progress','resolved','ignored','duplicate') COLLATE utf8mb3_unicode_ci NOT NULL DEFAULT 'new',
  `severity` enum('low','medium','high','critical') COLLATE utf8mb3_unicode_ci NOT NULL DEFAULT 'medium',
  `visibility` enum('reporter_and_staff','staff_only') COLLATE utf8mb3_unicode_ci NOT NULL DEFAULT 'reporter_and_staff',
  `title` varchar(255) COLLATE utf8mb3_unicode_ci NOT NULL,
  `description` mediumtext COLLATE utf8mb3_unicode_ci,
  `affected_module` varchar(100) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `affected_route` varchar(255) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `environment` varchar(50) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `error_class` varchar(255) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `error_code` varchar(100) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `error_message_sample` text COLLATE utf8mb3_unicode_ci,
  `stacktrace_sample` mediumtext COLLATE utf8mb3_unicode_ci,
  `first_seen_at` datetime NOT NULL,
  `last_seen_at` datetime NOT NULL,
  `occurrence_count` int unsigned NOT NULL DEFAULT '0',
  `report_count` int unsigned NOT NULL DEFAULT '0',
  `comment_count` int unsigned NOT NULL DEFAULT '0',
  `reporter_user_id` bigint unsigned DEFAULT NULL,
  `assigned_to_user_id` bigint unsigned DEFAULT NULL,
  `external_ticket_provider` enum('github','jira','none') COLLATE utf8mb3_unicode_ci NOT NULL DEFAULT 'none',
  `external_ticket_id` varchar(100) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `external_ticket_url` varchar(500) COLLATE utf8mb3_unicode_ci DEFAULT NULL,
  `duplicate_of_incident_id` bigint unsigned DEFAULT NULL,
  `resolution_summary` text COLLATE utf8mb3_unicode_ci,
  `resolved_at` datetime DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_incidents_public_code` (`public_code`),
  UNIQUE KEY `uq_incidents_open_fingerprint` (`open_fingerprint`),
  KEY `idx_incidents_status` (`status`),
  KEY `idx_incidents_severity` (`severity`),
  KEY `idx_incidents_reporter_user_id` (`reporter_user_id`),
  KEY `idx_incidents_assigned_to_user_id` (`assigned_to_user_id`),
  KEY `idx_incidents_module` (`affected_module`),
  KEY `idx_incidents_last_seen_at` (`last_seen_at`),
  KEY `idx_incidents_duplicate_of_incident_id` (`duplicate_of_incident_id`),
  CONSTRAINT `fk_incidents_duplicate_of` FOREIGN KEY (`duplicate_of_incident_id`) REFERENCES `incidents` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3 COLLATE=utf8mb3_unicode_ci;
